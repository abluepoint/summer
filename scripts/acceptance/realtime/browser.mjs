import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
const { chromium } = createRequire(process.cwd() + '/package.json')('playwright-core');
const result = { checks: [], networkMocking: false, pageErrors: 0 };
const check = (name, passed, facts = {}) => result.checks.push({ name, passed: Boolean(passed), ...facts });
const base = 'http://127.0.0.1:19573';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
process.on('SIGTERM', () => browser.close().finally(() => process.exit(1)));
let stage = 'login';
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(20000); page.on('pageerror', () => result.pageErrors++);
  const sent = [], frames = [], closes = [];
  page.on('websocket', socket => {
    socket.on('close', () => closes.push(true));
    socket.on('framesent', frame => { try { sent.push(JSON.parse(String(frame.payload))); } catch {} });
    socket.on('framereceived', frame => { try { frames.push(JSON.parse(String(frame.payload))); } catch {} });
  });
  await page.goto(base + '/auth-users');
  await page.locator('input[autocomplete="username"]').fill(process.env.SUMMER_E2E_USERNAME);
  await page.locator('input[autocomplete="current-password"]').fill(process.env.SUMMER_E2E_PASSWORD);
  await page.getByRole('button', { name: '登录', exact: true }).click();
  await page.waitForURL(base + '/auth-users');
  check('actual_chrome_pkce_login', true);
  stage = 'messages'; await page.goto(base + '/messages');
  await page.getByText('OPEN', { exact: true }).waitFor();
  check('same_origin_cookie_websocket_opens', frames.some(frame => frame.type === 'connected'));
  const text = '消息真实检查-' + Date.now();
  await page.getByPlaceholder('输入消息').fill(text);
  await page.getByRole('button', { name: '发送', exact: true }).click();
  await page.getByRole('cell', { name: text, exact: true }).waitFor();
  const row = page.getByRole('row').filter({ hasText: text });
  for (let index = 0; index < 50 && !frames.some(frame => frame.type === 'ack'); index++) await page.waitForTimeout(100);
  check('ui_sends_and_renders_persisted_message', sent.some(frame => frame.type === 'send') && frames.some(frame => frame.type === 'ack'));
  await row.getByRole('button', { name: '确认', exact: true }).click();
  await row.getByRole('cell', { name: 'ACKED', exact: true }).waitFor();
  check('ui_ack_updates_persistent_status', true);
  await page.reload(); await page.getByText('OPEN', { exact: true }).waitFor();
  await page.getByRole('row').filter({ hasText: text }).getByRole('cell', { name: 'ACKED', exact: true }).waitFor();
  check('reload_restores_durable_message_and_ack', true);
  await page.screenshot({ path: process.env.SUMMER_REALTIME_EVIDENCE_DIR + '/messages-success.png', fullPage: true });
  stage = 'invalid_payload';
  const input = page.getByPlaceholder('输入消息');
  await input.fill('x'.repeat(66000));
  await page.getByRole('button', { name: '发送', exact: true }).click();
  for (let index = 0; index < 50 && !frames.some(frame => frame.type === 'error'); index++) await page.waitForTimeout(100);
  const hasError = frames.some(frame => frame.type === 'error') || closes.length > 0;
  const visible = await page.locator('.arco-alert-error').count() > 0;
  check('socket_failure_is_visible_and_keeps_unsent_input', visible && await input.inputValue() !== '', { receivedErrorOrClose: hasError, visibleError: visible, inputPreserved: await input.inputValue() !== '' });
  await input.fill('');
  await page.screenshot({ path: process.env.SUMMER_REALTIME_EVIDENCE_DIR + '/messages-invalid.png', fullPage: true });
  stage = 'unauthorized';
  const restricted = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  restricted.setDefaultTimeout(20000); restricted.on('pageerror', () => result.pageErrors++);
  await restricted.goto(base + '/auth-users');
  await restricted.locator('input[autocomplete="username"]').fill(process.env.SUMMER_E2E_READER);
  await restricted.locator('input[autocomplete="current-password"]').fill(process.env.SUMMER_E2E_READER_PASSWORD);
  await restricted.getByRole('button', { name: '登录', exact: true }).click();
  await restricted.waitForURL(base + '/auth-users');
  await restricted.goto(base + '/messages');
  await restricted.getByText(/对不起，您没有访问该资源的权限/).last().waitFor();
  check('real_ungranted_user_is_denied_without_send_controls', await restricted.getByRole('button', { name: '发送', exact: true }).count() === 0);
  await restricted.screenshot({ path: process.env.SUMMER_REALTIME_EVIDENCE_DIR + '/messages-denied.png', fullPage: true });
  result.complete = true;
} catch (error) { result.complete = false; result.failureType = error.name; result.failureStage = stage; }
finally {
  result.passed = result.complete && result.pageErrors === 0 && result.checks.every(check => check.passed);
  await writeFile(process.env.SUMMER_REALTIME_EVIDENCE_DIR + '/browser-result.json', JSON.stringify(result, null, 2));
  await browser.close();
}
process.exitCode = result.passed ? 0 : 1;
