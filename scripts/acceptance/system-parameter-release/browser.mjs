import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
const { chromium } = createRequire(process.cwd() + '/package.json')('playwright-core');
const out = process.env.SUMMER_PARAMETER_RELEASE_EVIDENCE_DIR;
const base = 'http://127.0.0.1:19573';
const key = process.env.SUMMER_E2E_PARAMETER_KEY;
const root = '/api/v1/enterprises/ent-acme/system-parameters/' + key;
const result = { checks: [], networkMocking: false, pageErrors: 0, complete: false };
const check = (name, passed, facts = {}) => result.checks.push({ name, passed: Boolean(passed), ...facts });
let browser, page, stage = 'login';
async function login(context, username, password) {
  const next = await context.newPage({ viewport: { width: 1440, height: 1100 } });
  next.setDefaultTimeout(30000); next.on('pageerror', () => result.pageErrors++);
  await next.goto(base + '/system-parameters');
  await next.locator('input[autocomplete="username"]').fill(username);
  await next.locator('input[autocomplete="current-password"]').fill(password);
  await next.getByRole('button', { name: '登录', exact: true }).click();
  await next.waitForURL(base + '/system-parameters');
  return next;
}
const row = () => page.locator('.arco-table').first().getByRole('row').filter({ has: page.getByRole('cell', { name: key, exact: true }) });
const response = (method, path) => page.waitForResponse(r => r.request().method() === method && new URL(r.url()).pathname === path);
const history = () => page.locator('.arco-card').filter({ has: page.getByText('版本历史 · ' + key, { exact: true }) }).last();
const versionRow = (state, value) => history().getByRole('row').filter({ has: page.getByRole('cell', { name: state, exact: true }) }).filter({ has: page.getByRole('cell', { name: String(value), exact: true }) });
const value = () => page.locator('.arco-drawer .arco-form-item').filter({ has: page.getByText('值', { exact: true }) }).locator('input');
async function closeDrawer() {
  await page.locator('.arco-drawer-close-icon').click();
  const discard = page.locator('.arco-modal').getByRole('button', { name: '放弃修改', exact: true });
  if (await discard.count()) await discard.click();
  await page.locator('.arco-drawer').waitFor({ state: 'hidden' });
}
try {
  browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
  page = await login(await browser.newContext(), process.env.SUMMER_E2E_USERNAME, process.env.SUMMER_E2E_PASSWORD);
  await row().waitFor(); check('actual_pkce_parameter_management_page', true);
  let pending = response('GET', root + '/versions');
  await row().getByRole('button', { name: '版本历史', exact: true }).click();
  let observed = await pending;
  await versionRow('PUBLISHED', 10).waitFor();
  check('page_reads_initial_published_history', observed.status() === 200);
  stage = 'draft';
  await row().getByRole('button', { name: '编辑', exact: true }).click();
  await value().fill('20'); pending = response('POST', root + '/draft');
  await page.locator('.arco-drawer').getByRole('button', { name: '保存草稿', exact: true }).click();
  observed = await pending; const draft = await observed.json();
  check('page_saves_draft_without_changing_current_version', observed.status() === 201 && draft.data?.state === 'DRAFT' && draft.data?.version === 0);
  await closeDrawer(); await versionRow('DRAFT', 20).waitFor();
  check('draft_is_visible_in_history_while_active_value_is_unchanged', await row().getByRole('cell', { name: '10', exact: true }).count() === 1);
  stage = 'publish'; pending = response('POST', root + '/publish');
  await versionRow('DRAFT', 20).getByRole('button', { name: '发布', exact: true }).click();
  observed = await pending; const published = await observed.json();
  await row().getByRole('cell', { name: '20', exact: true }).waitFor();
  check('page_publishes_draft_and_displays_effective_value', observed.status() === 200 && published.data?.state === 'PUBLISHED' && published.data?.version === 1);
  await page.screenshot({ path: out + '/release-published.png', fullPage: true });
  stage = 'rollback'; pending = response('POST', root + '/rollback');
  await versionRow('PUBLISHED', 10).getByRole('button', { name: '回滚', exact: true }).click();
  observed = await pending; const rolled = await observed.json();
  await row().getByRole('cell', { name: '10', exact: true }).waitFor();
  check('page_rolls_back_to_old_revision', observed.status() === 200 && rolled.data?.state === 'ROLLED_BACK' && rolled.data?.version === 2);
  stage = 'deactivate'; pending = response('POST', root + '/deactivate');
  await row().getByRole('button', { name: '停用', exact: true }).click();
  observed = await pending; const inactive = await observed.json();
  await row().getByRole('cell', { name: 'INACTIVE', exact: true }).waitFor();
  check('page_deactivates_with_current_version', observed.status() === 200 && inactive.data?.state === 'INACTIVE' && inactive.data?.version === 3);
  pending = response('POST', root + '/rollback');
  await versionRow('PUBLISHED', 10).getByRole('button', { name: '回滚', exact: true }).click();
  observed = await pending; const restored = await observed.json();
  await row().getByRole('cell', { name: 'ACTIVE', exact: true }).waitFor();
  check('page_restores_active_version_after_deactivation', observed.status() === 200 && restored.data?.version === 4);
  await page.reload(); await row().waitFor();
  pending = response('GET', root + '/versions'); await row().getByRole('button', { name: '版本历史', exact: true }).click();
  observed = await pending; const restoredHistory = await observed.json();
  check('reload_retains_effective_version_and_release_history', observed.status() === 200 && restoredHistory.data?.currentVersion === 4 && restoredHistory.data?.items.some(item => item.state === 'ROLLED_BACK') && restoredHistory.data?.items.some(item => item.state === 'INACTIVE'));
  await page.screenshot({ path: out + '/release-restored.png', fullPage: true });
  stage = 'invalid_draft'; await row().getByRole('button', { name: '编辑', exact: true }).click();
  await value().fill('101'); pending = response('POST', root + '/draft');
  await page.locator('.arco-drawer').getByRole('button', { name: '保存草稿', exact: true }).click();
  observed = await pending; const invalid = await observed.json();
  check('invalid_draft_is_visible_with_request_id_and_keeps_input', observed.status() === 400 && invalid.error?.code === 'SUMMER_PARAMETER_INVALID' && await value().inputValue() === '101' && (await page.locator('.arco-drawer').innerText()).includes(invalid.requestId));
  await page.screenshot({ path: out + '/release-invalid.png', fullPage: true });
  await closeDrawer(); await page.close();
  stage = 'reader_denied';
  page = await login(await browser.newContext(), process.env.SUMMER_E2E_READER, process.env.SUMMER_E2E_READER_PASSWORD);
  await row().waitFor(); pending = response('GET', root + '/versions');
  await row().getByRole('button', { name: '版本历史', exact: true }).click(); await pending;
  pending = response('POST', root + '/publish');
  await versionRow('DRAFT', 20).getByRole('button', { name: '发布', exact: true }).click();
  observed = await pending; const denied = await observed.json();
  check('actual_reader_cannot_publish_and_sees_request_id', observed.status() === 403 && denied.error?.code === 'SUMMER_FORBIDDEN' && (await page.locator('.arco-alert-error').innerText()).includes(denied.requestId));
  await page.screenshot({ path: out + '/release-denied.png', fullPage: true });
  check('no_unhandled_page_errors', result.pageErrors === 0); result.complete = true;
} catch (error) {
  result.failureType = error.name; result.failureStage = stage;
  result.localFrames = error.stack?.match(/browser\.mjs:\d+:\d+/g) || [];
  if (page && result.checks.length) await page.screenshot({ path: out + '/browser-failed.png', fullPage: true }).catch(() => {});
} finally {
  await writeFile(out + '/browser-result.json', JSON.stringify(result, null, 2) + '\n');
  await browser?.close();
}
process.exitCode = result.complete && result.checks.every(item => item.passed) ? 0 : 1;
